"""Gate 2 measured in the browser: submit to visible comparison.

Ten variants x 250 stocks + SPY x five years (the capacity dataset) are submitted to
``POST /api/batches`` from the dashboard page; the clock stops when the Compare page
shows variant 1 against variant 2 with its first differing decision. Three consecutive
batches, finished-result reuse off. Needs the built dashboard (``make web``) and
Playwright's Chromium. Run: ``uv run python scripts/benchmark_browser.py``.
Writes ``docs/benchmarks/capacity-browser.md``.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
import tempfile
import time
from datetime import UTC, datetime
from pathlib import Path

import httpx

sys.path.insert(0, str(Path(__file__).parent))
import benchmark_capacity as cap
import make_capacity_dataset as dataset

from moneylab.service import Lab

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "docs" / "benchmarks" / "capacity-browser.md"
LIMIT_S = 120.0


def main() -> int:
    csv = dataset.DEFAULT_OUT
    if not csv.exists():
        dataset.write(csv)
    home = Path(tempfile.mkdtemp(prefix="moneylab-browser-bench-"))
    snap = Lab.open(home).import_file(csv, label="capacity 250x5y")
    configs = cap.variants(dataset.symbols())
    body = {"configs": [c.model_dump(mode="json") for c in configs], "snapshot_id": snap.id}
    body_path = home / "batch.json"
    body_path.write_text(json.dumps(body))

    port = 8799
    env = {**os.environ, "MONEYLAB_HOME": str(home)}
    server = subprocess.Popen(
        ["uv", "run", "moneylab", "serve", "--port", str(port)], cwd=ROOT, env=env
    )
    base = f"http://127.0.0.1:{port}"
    try:
        for _ in range(300):
            try:
                if httpx.get(f"{base}/api/health").status_code == 200:
                    break
            except httpx.HTTPError:
                time.sleep(0.1)
        workers = Lab.open(home).settings.workers
        out = subprocess.run(
            ["node", str(ROOT / "e2e" / "batch_visible.cjs"), base, str(body_path), "3"],
            check=True,
            capture_output=True,
            text=True,
        )
    finally:
        server.terminate()
        server.wait(timeout=30)
    rows = json.loads(out.stdout.strip().splitlines()[-1])
    passed = all(r["total_s"] < LIMIT_S for r in rows)
    mach = cap.machine()
    lines = [
        "# Capacity in the browser (acceptance gate 2)",
        "",
        f"Generated by `uv run python scripts/benchmark_browser.py` on "
        f"{datetime.now(UTC):%Y-%m-%d %H:%M} UTC.",
        "",
        f"**Result: {'PASS' if passed else 'FAIL'}** - three consecutive batches of ten "
        "variants x 250 stocks + SPY x five years, timed from submitting in the dashboard "
        "page to the Compare page showing variant 1 vs variant 2 with its first differing "
        f"decision (limit {LIMIT_S:.0f} s). Finished-result reuse is not implemented.",
        "",
        "| Batch | Submit to all runs saved (s) | Saved to comparison visible (s) | Total (s) |",
        "| --- | --- | --- | --- |",
        *[
            f"| {r['batch']} | {r['saved_s']:.2f} | {r['visible_s']:.2f} | {r['total_s']:.2f} |"
            for r in rows
        ],
        "",
        f"Machine: {mach.get('cpu', '?')}, {mach.get('cpus', '?')} CPUs, "
        f"{mach.get('ram_gb', 0):.1f} GiB RAM; workers setting {workers} (0 = one per CPU). "
        "Browser: headless Chromium via Playwright.",
        "",
    ]
    REPORT.write_text("\n".join(lines))
    print("\n".join(lines))
    shutil.rmtree(home, ignore_errors=True)
    return 0 if passed else 1


if __name__ == "__main__":
    raise SystemExit(main())
